-- Database baru website SDN 1 Beririjarak
-- Aman dijalankan berulang: tidak menghapus database atau data yang sudah ada.
CREATE DATABASE IF NOT EXISTS db_sdn1beririjarak_baru
  CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE db_sdn1beririjarak_baru;

CREATE TABLE IF NOT EXISTS tb_users (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  username VARCHAR(50) NOT NULL UNIQUE,
  password VARCHAR(255) NOT NULL,
  nama_lengkap VARCHAR(100) DEFAULT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS tb_guru (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  nip VARCHAR(30) DEFAULT NULL,
  nama_guru VARCHAR(150) NOT NULL,
  jenis_kelamin ENUM('Laki-laki','Perempuan') DEFAULT NULL,
  jabatan VARCHAR(100) DEFAULT NULL,
  pendidikan VARCHAR(100) DEFAULT NULL,
  foto VARCHAR(255) DEFAULT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS tb_siswa (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  nis VARCHAR(30) DEFAULT NULL,
  nisn VARCHAR(30) DEFAULT NULL,
  nama_siswa VARCHAR(150) NOT NULL,
  jenis_kelamin ENUM('Laki-laki','Perempuan') DEFAULT NULL,
  tempat_lahir VARCHAR(100) DEFAULT NULL,
  tanggal_lahir DATE DEFAULT NULL,
  alamat TEXT DEFAULT NULL,
  kelas VARCHAR(30) DEFAULT NULL,
  tahun_ajaran VARCHAR(20) DEFAULT NULL,
  status ENUM('Aktif','Lulus','Pindah') DEFAULT 'Aktif',
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS tb_berita (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  judul VARCHAR(200) NOT NULL,
  slug VARCHAR(220) DEFAULT NULL,
  isi LONGTEXT NOT NULL,
  gambar VARCHAR(255) DEFAULT NULL,
  tanggal_publikasi DATETIME DEFAULT CURRENT_TIMESTAMP,
  status ENUM('Draft','Terbit') DEFAULT 'Draft',
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS tb_galeri (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  judul VARCHAR(150) NOT NULL,
  deskripsi TEXT DEFAULT NULL,
  nama_file VARCHAR(255) NOT NULL,
  tanggal_kegiatan DATE DEFAULT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS tb_media (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  judul VARCHAR(200) NOT NULL,
  deskripsi TEXT DEFAULT NULL,
  mata_pelajaran VARCHAR(100) DEFAULT NULL,
  kelas VARCHAR(30) DEFAULT NULL,
  jenis_media ENUM('Video','Dokumen','Link','Gambar','Lainnya') DEFAULT 'Lainnya',
  file_media VARCHAR(255) DEFAULT NULL,
  link_media VARCHAR(500) DEFAULT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS tb_profil (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  nama_sekolah VARCHAR(150) NOT NULL,
  npsn VARCHAR(30) DEFAULT NULL,
  alamat TEXT DEFAULT NULL,
  telepon VARCHAR(30) DEFAULT NULL,
  email VARCHAR(100) DEFAULT NULL,
  visi TEXT DEFAULT NULL,
  misi LONGTEXT DEFAULT NULL,
  sambutan_kepala_sekolah LONGTEXT DEFAULT NULL,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

